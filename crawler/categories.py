# Offer-type axis (small, flat — no per-value metadata needed).
OFFER_TYPES: tuple[str, ...] = (
    "credit", "grant", "vps", "domain", "license",
    "subscription", "code", "giveaway", "other",
)

# --------------------------------------------------------------------------- #
# Derived lookups
# --------------------------------------------------------------------------- #
CATEGORIES: tuple[str, ...] = tuple(d.key for d in CATEGORY_DEFS)
CATEGORY_BY_KEY: dict[str, CategoryDef] = {d.key: d for d in CATEGORY_DEFS}

DEFAULT_CATEGORY = "other"
DEFAULT_OFFER_TYPE = "other"


# --------------------------------------------------------------------------- #
# Coercion / validation
# --------------------------------------------------------------------------- #
def is_valid_category(value: str) -> bool:
    return value in CATEGORY_BY_KEY


def coerce_category(value: str | None) -> str:
    """Normalize an LLM-provided category to a known key, else 'other'."""
    v = (value or DEFAULT_CATEGORY).lower().strip()
    return v if v in CATEGORY_BY_KEY else DEFAULT_CATEGORY


def coerce_offer_type(value: str | None) -> str:
    """Normalize an LLM-provided offer_type to a known value, else 'other'."""
    v = (value or DEFAULT_OFFER_TYPE).lower().strip()
    return v if v in OFFER_TYPES else DEFAULT_OFFER_TYPE


# --------------------------------------------------------------------------- #
# Prompt rendering — both styles derive from the same defs, so single- and
# batch-mode prompts can never drift apart.
# --------------------------------------------------------------------------- #
def category_prompt_block() -> str:
    """Verbose 'key — description' block for the single-item SYSTEM_PROMPT."""
    return "\n".join(f"{d.key:<15} — {d.description}" for d in CATEGORY_DEFS)


def category_prompt_csv() -> str:
    """Compact comma-separated key list for the batch prompt."""
    return ", ".join(CATEGORIES)


def offer_type_prompt_csv() -> str:
    return " | ".join(OFFER_TYPES)
