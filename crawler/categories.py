"""
crawler/categories.py — THE single source of truth for the offer taxonomy
==========================================================================
Every category value, its emoji badge, its Discord embed color, and its
prompt-facing description lives here and ONLY here. Anything that needs the
taxonomy — the LLM prompts (verifier), the Discord dispatcher, the schema
CHECK constraint (mirrored, see below), the scheduler assertion, and the
dashboard TypeScript (generated by scripts/sync_categories.py) — derives
from `CATEGORY_DEFS`.

Why this exists: the taxonomy was previously copy-pasted across 8+ places in
three different value sets, guaranteeing drift. This module removes every
duplicate definition.

Note on Postgres: `schema.sql` still hardcodes the CHECK constraint because
Postgres cannot import Python. `tests/test_categories.py` asserts the two
lists stay in sync, so a change here that isn't mirrored in schema.sql fails
the test suite.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class CategoryDef:
    """One offer category: its stable key, UI badge, embed color, and doc."""

    key: str
    emoji: str
    color: int          # Discord decimal color (also rendered as hex for the dashboard)
    description: str     # shown to the LLM in the extraction prompt

    @property
    def hex_color(self) -> str:
        return f"#{self.color:06X}"


# --------------------------------------------------------------------------- #
# THE canonical 15-value taxonomy. Order is stable and meaningful (prompt
